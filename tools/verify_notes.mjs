#!/usr/bin/env node
// End-to-end acceptance on a disposable local D1 database, real API, adapter,
// workbench and Chromium. No deployment, production writes or external requests.
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const arg = name => { const i = process.argv.indexOf(name); return i < 0 ? null : process.argv[i + 1]; };
const OUT = path.resolve(arg('--out') || fs.mkdtempSync(path.join(os.tmpdir(), 'versforms-notes-evidence-')));
if (fs.existsSync(OUT) && fs.readdirSync(OUT).length) throw new Error('Evidence directory must be empty.');
fs.mkdirSync(OUT, { recursive: true });
const SCRATCH = fs.mkdtempSync(path.join(os.tmpdir(), 'versforms-notes-runtime-'));
process.env.STUDIO_CF_SCRATCH = path.join(SCRATCH, 'runtime');
const require = createRequire(import.meta.url);
const { chromium } = require(arg('--playwright') || path.join(process.env.CODEX_PRIMARY_RUNTIME_NODE_MODULES || '', 'playwright'));
const CHROME = arg('--chrome') || process.env.CHROME_BIN;
if (!CHROME || !fs.existsSync(CHROME)) throw new Error('Supply --chrome with a local Chromium executable.');
const { makeKey, signRS256, claims, startJwks } = await import('../studio-cf/tests/helpers/jwt.mjs');
const { startPagesDev } = await import('../studio-cf/tests/helpers/wrangler.mjs');
const MODEL = await import('../studio/notes-model.mjs');
const hash = p => createHash('sha256').update(fs.readFileSync(path.join(ROOT, p))).digest('hex');
const protectedPaths = ['site/data/j.json', 'studio/data/review.json', 'release/public.json', 'studio/index.html', 'site/index.html'];
const beforeHashes = Object.fromEntries(protectedPaths.map(p => [p, hash(p)]));
const checks = [], errors = [], blockedRequests = [];
function pass(name, detail = true) { checks.push({ name, pass: true, detail }); console.log('PASS ' + name); }
const tokenOwner = 'fixture-owner@example.test', aud = 'notes-local-fixture';
let jwks, browser, first, restored;
const pages = [];
let activePage = null;
try {
  const sourceCheck = spawnSync('python3', ['tools/notes_sources.py', '--check'], { cwd: ROOT, encoding: 'utf8' });
  assert.equal(sourceCheck.status, 0, sourceCheck.stderr || sourceCheck.stdout);
  const dist = path.join(SCRATCH, 'dist');
  const build = spawnSync('python3', ['studio-cf/build_dist.py', '--out', dist], { cwd: ROOT, encoding: 'utf8' });
  assert.equal(build.status, 0, build.stderr || build.stdout);
  const key = makeKey('notes-fixture-kid'); jwks = await startJwks({ keys: [key] });
  const team = `127.0.0.1:${jwks.port}`, iss = 'https://' + team;
  const vars = { ACCESS_TEAM_DOMAIN: team, ACCESS_AUD: aud, OWNER_EMAILS: tokenOwner, ACCESS_JWKS_URL_TEST: `http://${team}/cdn-cgi/access/certs` };
  const token = () => signRS256(key, claims({ iss, aud, email: tokenOwner }));
  first = await startPagesDev(vars, 'notes-first', { dir: dist });
  for (const route of ['/notes.html', '/notes-model.mjs', '/data/notes-versions.json', '/api/db/notes', '/artifact-preview.html', '/artifact-model.mjs', '/site/reader-features.js', '/api/db/artifacts']) {
    const result = await fetch(first.base + route); assert.equal(result.status, 403); assert.equal((await result.text()).length, 0);
  }
  pass('private static files and notes API deny unauthenticated access');
  const api = async (srv, coll, id, data) => {
    const r = await fetch(srv.base + '/api/db/' + coll + (id ? '/' + id : ''), { headers: { 'Cf-Access-Jwt-Assertion': token(), ...(data ? { 'content-type': 'application/json' } : {}) }, ...(data ? { method: 'PUT', body: JSON.stringify(data) } : {}) });
    assert.ok(r.ok, `API ${coll} ${r.status}`); return r.json();
  };
  browser = await chromium.launch({ executablePath: CHROME, headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage'] });
  async function pageFor(srv, viewport = { width: 1280, height: 900 }, colorScheme = 'light') {
    const context = await browser.newContext({ viewport, colorScheme, acceptDownloads: true, serviceWorkers: 'block', extraHTTPHeaders: { 'Cf-Access-Jwt-Assertion': token() } });
    await context.route('**/*', route => {
      if (new URL(route.request().url()).origin === srv.base) return route.continue();
      blockedRequests.push(route.request().url()); return route.abort();
    });
    const page = await context.newPage(); pages.push(context); activePage = page;
    page.on('pageerror', e => errors.push(e.message));
    await page.goto(srv.base + '/index.html');
    await page.locator('a[href="notes.html"]').click();
    await page.waitForFunction(() => document.getElementById('connection')?.textContent.includes('Connected'), { timeout: 20000 });
    return page;
  }
  const page = await pageFor(first);
  assert.equal((await api(first, 'notes')).docs.length, 0);
  assert.equal(await page.locator('#reader-notes').evaluate(e => e.hidden && e.childNodes.length === 0), true);
  pass('existing source without notes opens with empty hidden notes');
  await page.selectOption('#piece', 'p001'); await page.selectOption('#version', 'p001-diary1-0'); await page.selectOption('#line', 'diary1-0-0');
  await page.fill('#author-id', 'fixture-author'); await page.fill('#credit', 'Technical fixture author');
  await page.fill('#reviewer', 'fixture-editor'); await page.selectOption('#content-provenance', 'technical-fixture');
  await page.fill('#note-date', '2026-11-04'); await page.fill('#note-text', 'TECHNICAL FIXTURE — note revision one');
  await page.selectOption('#visibility', 'public-candidate');
  await page.locator('details').filter({ has: page.locator('#citation-label') }).locator('summary').click();
  await page.fill('#citation-label', 'TECHNICAL FIXTURE reference'); await page.fill('#citation-locator', 'fixture section');
  await page.click('#save-note');
  await page.waitForFunction(() => document.getElementById('save-status').textContent.startsWith('Saved and read back'));
  const firstNotes = (await api(first, 'notes')).docs.map(d => d.data);
  assert.equal(firstNotes.length, 1); assert.equal(firstNotes[0].anchor.versionId, 'p001-diary1-0'); assert.equal(firstNotes[0].anchor.lineId, 'diary1-0-0');
  assert.equal(firstNotes[0].citations[0].url, undefined); assert.equal(firstNotes[0].editedBy, 'fixture-editor');
  const noteId = firstNotes[0].recordId;
  pass('authoring persists exact source, distinct editor and label-only citation');
  await page.fill('#note-text', 'TECHNICAL FIXTURE — note revision two'); await page.fill('#note-date', '2026-11-05');
  assert.equal(await page.locator('#accept-note').isEnabled(), false); assert.equal(await page.locator('#record').isEnabled(), false);
  await page.click('#save-note'); await page.waitForFunction(() => document.getElementById('save-status').textContent.startsWith('Saved and read back'));
  const revisions = (await api(first, 'notes')).docs.map(d => d.data);
  assert.equal(revisions.length, 2); assert.ok(revisions.some(d => d.noteDate === '2026-11-04' && d.text.endsWith('one'))); assert.ok(revisions.some(d => d.noteDate === '2026-11-05' && d.text.endsWith('two')));
  pass('editing preserves both dates and revisions; unsaved text blocks review and record switching');
  await page.click('#accept-note'); await page.waitForFunction(() => document.getElementById('record-status').textContent.includes('accepted'));
  await page.click('#clear-note'); await page.waitForFunction(() => document.getElementById('record-status').textContent.includes('cleared'));
  assert.equal(await page.locator('#reader-notes').evaluate(e => e.hidden && !e.childNodes.length), true);
  await page.click('#reveal-notes');
  await page.locator('#reader-notes').getByText('TECHNICAL FIXTURE — note revision two', { exact: true }).waitFor();
  await page.locator('#preview').screenshot({ path: path.join(OUT, 'reader-cleared-desktop.png') });
  const beforePlacement = (await api(first, 'notes')).docs.map(d => d.data);
  await page.selectOption('#preview-placement', 'margin');
  await page.click('#reveal-notes');
  assert.ok(await page.locator('#reader-notes').evaluate(e => e.getBoundingClientRect().left > document.getElementById('reader-poem').getBoundingClientRect().left + 100));
  await page.locator('#preview').screenshot({ path: path.join(OUT, 'reader-margin-proposal.png') });
  assert.deepEqual((await api(first, 'notes')).docs.map(d => d.data), beforePlacement);
  await page.selectOption('#preview-placement', 'below');
  await page.click('#reveal-notes');
  await page.locator('#reader-notes section').focus();
  await page.locator('#participation details summary').click();
  await page.locator('#participation').screenshot({ path: path.join(OUT, 'participation-and-timing-options.png') });
  assert.equal(await page.locator('#participation button:not(:disabled)').count(), 0);
  pass('placement and date-only timing previews leave invitations and submissions inactive');
  await page.click('#reveal-notes');
  await page.locator('#reader-notes section').focus();
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#reader-notes').evaluate(e => e.hidden && !e.childNodes.length), true);
  assert.equal(await page.evaluate(() => document.activeElement.id), 'reveal-notes');
  pass('accepted and cleared fixture reveals only on request; Escape empties DOM and restores focus');
  const downloadPromise = page.waitForEvent('download'); await page.click('#export-notes'); const download = await downloadPromise;
  await download.saveAs(path.join(OUT, 'notes-fixture-backup.json'));
  const exported = JSON.parse(fs.readFileSync(path.join(OUT, 'notes-fixture-backup.json')));
  restored = await startPagesDev(vars, 'notes-restored', { dir: dist });
  const other = await pageFor(restored);
  const corrupt = Buffer.from(JSON.stringify(exported).replace('TECHNICAL FIXTURE', 'INVALID_BYTE_FIXTURE'));
  corrupt[corrupt.indexOf('INVALID_BYTE_FIXTURE')] = 0xff;
  await other.setInputFiles('#restore-notes', { name: 'invalid-utf8.json', mimeType: 'application/json', buffer: corrupt });
  await other.waitForFunction(() => document.getElementById('backup-status').classList.contains('error'));
  assert.equal((await api(restored, 'notes')).docs.length, 0);
  pass('malformed UTF-8 backup is rejected before any restore write');
  await other.setInputFiles('#restore-notes', path.join(OUT, 'notes-fixture-backup.json'));
  await other.waitForFunction(() => document.getElementById('backup-status').textContent.startsWith('Restored'));
  const restoredNotes = (await api(restored, 'notes')).docs.map(d => d.data);
  const sorted = a => [...a].sort((x, y) => x.revisionId.localeCompare(y.revisionId));
  assert.deepEqual(sorted(restoredNotes), sorted(exported.notes));
  await other.reload(); await other.waitForFunction(() => document.getElementById('connection').textContent.includes('Connected'));
  await other.selectOption('#record', noteId); assert.equal(await other.inputValue('#note-text'), 'TECHNICAL FIXTURE — note revision two');
  pass('browser export restores every revision into an empty independent D1 database and survives reload', { revisions: restoredNotes.length });
  await other.click('#new-note'); await other.selectOption('#family', 'contribution'); await other.selectOption('#kind', 'critical-note');
  await other.fill('#author-id', 'fixture-contributor-private-id'); await other.fill('#credit', 'Technical fixture contributor');
  await other.fill('#reviewer', 'fixture-editor'); await other.selectOption('#content-provenance', 'technical-fixture');
  await other.fill('#note-text', 'TECHNICAL FIXTURE — contribution metadata demonstration'); await other.selectOption('#visibility', 'public-candidate');
  await other.selectOption('#permission-state', 'granted'); await other.check('#permission-web'); await other.fill('#permission-evidence', 'TECHNICAL FIXTURE — simulated permission evidence, not a real grant');
  await other.click('#save-note'); await other.waitForFunction(() => document.getElementById('save-status').textContent.startsWith('Saved and read back'));
  await other.click('#accept-note'); await other.waitForFunction(() => document.getElementById('record-status').textContent.includes('accepted'));
  await other.click('#clear-note'); await other.waitForFunction(() => document.getElementById('record-status').textContent.includes('cleared'));
  await other.click('#reveal-notes'); await other.locator('#reader-notes').getByText('Technical fixture contributor', { exact: true }).waitFor();
  const rendered = await other.locator('#reader-notes').innerText(); assert.ok(!rendered.includes('fixture-contributor-private-id')); assert.ok(!rendered.includes('simulated permission evidence'));
  for (const collection of ['release', 'versions', 'rconfig', 'decisions']) assert.equal((await api(restored, collection)).docs.length, 0);
  const contributionDocs = (await api(restored, 'contributions')).docs.map(d => d.data); assert.equal(contributionDocs.length, 3); assert.equal(contributionDocs[0].participation.placement, 'around');
  assert.equal(contributionDocs[0].participation.countsTowardsAuthor100, false);
  pass('contribution reviewed and credited without changing author poem/version/release/numbering collections');
  const source = MODEL.buildSourceCatalog(JSON.parse(fs.readFileSync(path.join(ROOT, 'studio/data/notes-versions.json'))), JSON.parse(fs.readFileSync(path.join(ROOT, 'studio/data/review.json'))));
  const projection = MODEL.projectRecords([...restoredNotes, ...contributionDocs], source, { mode: 'public', versions: [{ pieceId: 'p001', versionId: 'p001-diary1-0' }] });
  assert.deepEqual(projection.records, []);
  assert.ok(!JSON.stringify(projection).includes(noteId));
  fs.writeFileSync(path.join(OUT, 'public-projection.json'), JSON.stringify({ records: projection.records }, null, 2) + '\n');
  pass('cleared private technical fixtures are absent from public projection');
  const mobile = await pageFor(restored, { width: 390, height: 844 }, 'dark');
  await mobile.selectOption('#piece', 'p001'); await mobile.selectOption('#version', 'p001-diary1-0'); await mobile.click('#reveal-notes');
  await mobile.locator('#preview').screenshot({ path: path.join(OUT, 'reader-cleared-phone-emulation.png') });
  assert.ok(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  pass('390px dark-mode preview fits viewport', 'Chromium emulation; no physical phone claim');
  const preservedAnchor = restoredNotes.find(r => r.recordId === noteId).anchor;
  await api(restored, 'reviews', 'diary1-0-0', { original: 'The walls', text: 'TECHNICAL FIXTURE — changed source line', status: 'corrected', at: new Date().toISOString() });
  await other.selectOption('#record', noteId);
  await other.waitForFunction(() => document.getElementById('anchor-warning').textContent.includes('It is preserved.'), { timeout: 15000 });
  assert.equal(await other.locator('#reader-notes').evaluate(e => e.hidden && !e.childNodes.length), true);
  const afterChange = (await api(restored, 'notes')).docs.map(d => d.data);
  assert.deepEqual(afterChange.find(r => r.revisionId === restoredNotes[0].revisionId).anchor, restoredNotes[0].anchor);
  assert.deepEqual(afterChange.find(r => r.recordId === noteId).anchor, preservedAnchor);
  await other.locator('#editor').screenshot({ path: path.join(OUT, 'invalid-anchor.png') });
  pass('source correction invalidates anchor and empties preview without moving stored notes');
  await page.goto(first.base + '/index.html');
  await page.locator('a[href="artifact-preview.html"]').click();
  await page.waitForFunction(() => document.getElementById('connection')?.textContent.includes('Connected') && !document.getElementById('editing').disabled);
  await page.selectOption('#piece', 'p001'); await page.selectOption('#version', 'p001-diary1-0');
  await page.selectOption('#kind', 'pronunciation'); await page.fill('#by', 'Technical fixture reviewer');
  await page.fill('#payload', JSON.stringify({entries:[{lineId:'diary1-0-0',token:'The',pronunciation:'TECHNICAL FIXTURE supplied pronunciation'}]}));
  await page.click('#save-artifact'); await page.waitForFunction(() => document.getElementById('save-status').textContent.startsWith('Saved and read back'));
  let artifacts = (await api(first, 'artifacts')).docs.map(d => d.data);
  assert.equal(artifacts.length, 1); const artifactId = artifacts[0].recordId, previousRevision = artifacts[0].revisionId;
  await page.fill('#payload', JSON.stringify({entries:[{lineId:'diary1-0-0',token:'The',pronunciation:'TECHNICAL FIXTURE revised supplied pronunciation'}]}));
  await page.fill('#reason', 'Technical fixture revision'); await page.click('#save-artifact');
  await page.waitForFunction(previous => document.getElementById('save-status').textContent.startsWith('Saved and read back') && !document.getElementById('save-status').textContent.endsWith(previous), previousRevision);
  artifacts = (await api(first, 'artifacts')).docs.map(d => d.data);
  assert.equal(artifacts.length, 2); assert.ok(artifacts.some(r => r.parents.includes(previousRevision)));
  await page.reload(); await page.waitForFunction(() => document.getElementById('connection')?.textContent.includes('Connected'));
  await page.selectOption('#record', artifactId); assert.equal(await page.locator('#artifact-history details').count(), 2);
  assert.match(await page.locator('#payload').inputValue(), /revised supplied pronunciation/);
  const artifactDownloadPromise = page.waitForEvent('download'); await page.click('#export-artifacts'); const artifactDownload = await artifactDownloadPromise;
  await artifactDownload.saveAs(path.join(OUT, 'artifacts-fixture-backup.json'));
  assert.equal(JSON.parse(fs.readFileSync(path.join(OUT, 'artifacts-fixture-backup.json'), 'utf8')).artifacts.length, 2);
  pass('built Studio artifact entry persists pronunciation revisions, reloads history and exports exact source bindings');
  const latestArtifact = artifacts.find(r => r.parents.includes(previousRevision));
  await page.check('#enable-preview'); await page.fill('#preview-config',JSON.stringify({audio:{url:'/unrequested-private-fixture.wav',source:latestArtifact.source}}));
  await page.click('#mount-preview');
  assert.match(await page.locator('#preview-status').innerText(), /selected stored artifact revision/);
  await page.fill('#preview-config',JSON.stringify({audio:{url:'/unrequested-private-fixture.wav',source:latestArtifact.source,revisionId:latestArtifact.revisionId}}));
  await page.click('#mount-preview');
  assert.equal(await page.locator('#feature-preview').getByRole('button',{name:'Audio',exact:true}).count(),1);
  assert.equal(await page.locator('audio').count(),0);
  pass('stored artifact preview requires its exact source and revision before preparing inactive controls');
  await api(first, 'reviews', 'diary1-0-0', {original:'The walls',text:'TECHNICAL FIXTURE changed artifact source',status:'corrected',at:new Date().toISOString()});
  await page.getByText('Source changed: this artifact is stale. Review and explicitly rebind before previewing.', {exact:true}).waitFor();
  await page.check('#enable-preview'); await page.click('#mount-preview');
  assert.match(await page.locator('#preview-status').innerText(), /Resolve the stored artifact source/);
  assert.equal(await page.locator('#feature-preview').evaluate(e => e.childNodes.length), 0);
  pass('source correction marks stored artifacts stale and blocks private preview until explicit rebind');
  for (const p of protectedPaths) assert.equal(hash(p), beforeHashes[p]);
  assert.deepEqual(errors, []); assert.deepEqual(blockedRequests.filter(url => !url.startsWith('https://fonts.googleapis.com/css2?')), []);
  pass('author data, shared studio/reader pages and release whitelist remain byte-identical');
  pass('no browser exceptions; only the existing Studio font stylesheet is requested off-origin and blocked', {blockedFontRequests:blockedRequests.length});
  fs.writeFileSync(path.join(OUT, 'acceptance.json'), JSON.stringify({ status: 'PASS', observedAt: new Date().toISOString(), browser: await browser.version(), node: process.version, checks, sourceHashes: beforeHashes, physicalDevice: 'not tested', scratch: SCRATCH }, null, 2) + '\n');
} catch (error) {
  if (activePage) { try { await activePage.screenshot({ path: path.join(OUT, 'failure.png'), fullPage: true }); fs.writeFileSync(path.join(OUT, 'failure-state.txt'), await activePage.locator('body').innerText()); } catch {} }
  fs.writeFileSync(path.join(OUT, 'acceptance.json'), JSON.stringify({ status: 'FAIL', observedAt: new Date().toISOString(), checks, error: error.stack, errors, blockedRequests }, null, 2) + '\n');
  console.error(error); process.exitCode = 1;
} finally {
  for (const context of pages) await context.close().catch(() => {});
  if (browser) await browser.close();
  if (first) await first.stop(); if (restored) await restored.stop(); if (jwks) await jwks.close();
}
